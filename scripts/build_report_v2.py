def set_font(run, ea=SONG, ascii_=TIMES, size=12, bold=False, color=None, italic=False):
    run.font.name = ascii_
    run._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), ea)
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
