# ================= 7 总结 =================
h1("7", "总结与结论")
para("本项目以 4 块 NASA 老化电池为对象，完成从数据清洗、退化建模到维护决策的完整流程，主要结论五条，由模型层面递进至决策层面：")
para("① 寿命是依赖阈值口径的统计量而非固定常数。阈值移动 ±0.05 Ah，寿命读数变动 30–40 循环；"
     "而寿命序关系在 80 个阈值取值上保持不变。寿命点估计的引用必须附带阈值口径。", indent=True)
para("② 高训练精度不构成外推能力的证据。随机森林训练 R² 0.997、测试 R² 全负，根源在于树模型函数类不包含趋势成分；"
     "双指数参数更多却在三块电池上显著更差，根源在于函数形式引入的系统性偏差。", indent=True)
para("③ 不确定性的主要来源不限于观测噪声。定义层与模型形式层（11–20 / 0–22 循环）与数据层（6–20 循环）处于同一量级；"
     "阈值口径的固定应先于模型优化。", indent=True)
para("④ 区间宽度与预测精度相互独立。名义 90% 区间实际覆盖 63%，缺口主要由点预测偏差驱动；"
     "区间收敛亦不构成预测正确的充分条件（B0006 稳定与命中时刻相差 10 个循环）。", indent=True)
para("⑤ 维护判据须将口径约定与不确定性分离报告。更换时刻 = 更严阈值穿越点 − 模型与数据裕度，"
     "保守口径以提前 26.3%–41.6% 寿命为代价避免滞后失效；对预测稳定时刻晚于更换点的个体，不等待预测收敛，直接安排更换。", indent=True)
para("对电池使用与维护的建议：对无人设备运营方，应将 EOL 阈值、裕度口径与切分点写入维护规范，"
     "按 S1–S3 流程执行，即先固定阈值，到达稳定时刻后采信模型输出，按保守口径排定更换；"
     "对本数据这类小样本场景，跨个体模型（任务 B）暂不具备可依赖性，逐个体建模为当前唯一可靠路径。")
para("局限性与后续方向：样本仅 4 块（有标签 3 块），跨个体结论只能作方向性描述；"
     "恒温数据无法研究温度效应；M4 的区间未含模型形式层，覆盖率缺口需更多个体数据才能严格补齐；"
     "后续可引入更多批次个体、非平稳核或生存分析处理右删失，并把容量以外的量测（内阻、温度）纳入特征。")

